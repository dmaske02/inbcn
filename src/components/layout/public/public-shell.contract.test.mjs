import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("the public shell preserves the approved logo, sticky header, and mobile menu contract", async () => {
  const header = await readFile(new URL("./header.tsx", import.meta.url), "utf8");

  assert.match(header, /import \{ Logo \} from "@\/components\/layout\/logo"/);
  assert.match(header, /<Logo href=\{`\/\$\{locale\}`\}/);
  assert.match(header, /sticky top-0/);
  assert.match(header, /hidden[^"\n]*lg:block/);
});

test("root metadata identifies INBCN instead of the framework starter", async () => {
  const layout = await readFile(
    new URL("../../../app/layout.tsx", import.meta.url),
    "utf8",
  );

  assert.match(layout, /title:\s*"INBCN/);
  assert.doesNotMatch(layout, /Create Next App|Generated by create next app/);
});
